import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { NextRequest } from "next/server";
import { prisma } from "../lib/db";
import { initializeCompanyChart } from "../lib/accounting/company-chart";
import { POST as createAdvance, DELETE as cancelAdvance } from "../app/api/accounting/employee-advances/route";
import { POST as createSalary } from "../app/api/hr/salaries/route";
import { PUT as editSalary, PATCH as statusSalary, DELETE as deleteSalary } from "../app/api/hr/salaries/[batchId]/route";
import { GET as preview } from "../app/api/hr/salaries/advance-deductions/route";
import { advanceSchema } from "../lib/hr/employee-advances";
import { restoreSalaryAdjustments } from "../lib/hr/salary-adjustments";

async function main() {
  const [{ db }] = await prisma.$queryRaw<Array<{ db: string }>>`SELECT DATABASE() AS db`;
  assert.equal(db, "rashidgroup_test");
  const group = await prisma.group.findFirstOrThrow();
  const user = await prisma.user.findFirstOrThrow({ select: { id: true } });
  const companyId = randomUUID(); const otherId = randomUUID();
  const headers = { "content-type": "application/json", "x-user-id": user.id, "x-user-email": "advance-test@example.invalid", "x-user-superadmin": "true" };
  const req = (body: unknown, method = "POST") => new NextRequest("http://localhost/api/test", { method, headers, body: JSON.stringify(body) });
  const ctx = (batchId: string) => ({ params: Promise.resolve({ batchId }) });
  const ok = async (response: Response, status = 200) => { const data = await response.json(); assert.equal(response.status, status, JSON.stringify(data)); return data.data; };
  try {
    await prisma.company.createMany({ data: [companyId, otherId].map(id => ({ id, groupId: group.id, nameAr: "Advances test", type: "GENERAL_TRADING" })) });
    await prisma.$transaction(tx => initializeCompanyChart(tx, companyId, "GENERAL_TRADING"));
    const employee = await prisma.employee.create({ data: { companyId, nameAr: "موظف السلفة", type: "OFFICE_EMPLOYEE" } });
    const outsider = await prisma.employee.create({ data: { companyId: otherId, nameAr: "Other company", type: "OFFICE_EMPLOYEE" } });
    const cash = await prisma.chartOfAccount.findUniqueOrThrow({ where: { companyId_code: { companyId, code: "1000" } } });
    const input = { companyId, employeeId: employee.id, amount: 300, date: "2026-09-27", cashAccountId: cash.id, installments: [{ year: 2026, month: 9, amount: 100 }, { year: 2026, month: 11, amount: 125 }, { year: 2027, month: 1, amount: 75 }] };
    assert(!advanceSchema.safeParse({ ...input, amount: 301 }).success);
    assert(!advanceSchema.safeParse({ ...input, installments: [input.installments[0], input.installments[0]], amount: 200 }).success);
    assert(!advanceSchema.safeParse({ ...input, date: "2026-02-30" }).success);
    assert.equal((await createAdvance(req({ ...input, employeeId: outsider.id }))).status, 400);
    assert.equal((await createAdvance(req({ ...input, cashAccountId: "invalid" }))).status, 400);
    const advance = await ok(await createAdvance(req(input)), 201);
    const journal = await prisma.journalEntry.findUniqueOrThrow({ where: { id: advance.journalEntryId }, include: { lines: true } });
    assert.equal(journal.status, "DRAFT"); assert.equal(Number(journal.totalDebit), 300); assert.equal(Number(journal.totalCredit), 300);
    assert.equal(journal.lines.find(line => line.accountId === cash.id)?.credit.toString(), "300");
    const previewAmounts = await ok(await preview(new NextRequest(`http://localhost/api/hr/salaries/advance-deductions?companyId=${companyId}&year=2026&month=9`, { headers })));
    assert.equal(previewAmounts[employee.id], 100);
    const payment = { employeeId: employee.id, baseAmount: 400, deductions: 10 };
    const salaryInput = { companyId, year: 2026, month: 9, payments: [payment] };
    assert.equal((await createSalary(req({ ...salaryInput, payments: [{ ...payment, employeeId: outsider.id }] }))).status, 400);
    assert.equal((await createSalary(req({ ...salaryInput, payments: [{ ...payment, baseAmount: 50 }] }))).status, 400);
    assert.equal(await prisma.salaryBatch.count({ where: { companyId } }), 0);
    const batch = await ok(await createSalary(req(salaryInput)), 201);
    assert.equal(Number(batch.payments[0].advanceDeduction), 100);
    assert.equal(Number(batch.payments[0].deductions), 110);
    assert.equal(Number(batch.payments[0].netAmount), 290);
    const salaryJournal = await prisma.journalEntry.findUniqueOrThrow({ where: { id: batch.journalEntryId }, include: { lines: { include: { account: true } } } });
    assert.equal(Number(salaryJournal.totalDebit), 390);
    assert.equal(Number(salaryJournal.lines.find(line => line.account.code === "1050")?.credit), 100);
    assert.equal(Number(salaryJournal.lines.find(line => line.account.code === "1010")?.credit), 290);
    assert.equal((await cancelAdvance(req({ id: advance.id }, "DELETE"))).status, 400);
    await ok(await editSalary(req({ year: 2026, month: 9, payments: [payment] }, "PUT"), ctx(batch.id)));
    let stored = await prisma.salaryBatch.findUniqueOrThrow({ where: { id: batch.id }, include: { payments: true, items: true } });
    assert.equal(Number(stored.payments[0].deductions), 110, "Re-edit does not double deduct");
    assert.equal(stored.items.filter(item => item.type === "EMPLOYEE_ADVANCE_DEDUCTION").length, 1);
    const adjustments = restoreSalaryAdjustments(stored.items.map(item => ({ ...item, amount: Number(item.amount) })), employee.id, false);
    assert.equal(adjustments.deductions?.reduce((sum, item) => sum + item.amount, 0), 10);
    await ok(await editSalary(req({ year: 2026, month: 10, payments: [payment] }, "PUT"), ctx(batch.id)));
    stored = await prisma.salaryBatch.findUniqueOrThrow({ where: { id: batch.id }, include: { payments: true, items: true } });
    assert.equal(Number(stored.payments[0].advanceDeduction), 0);
    assert.equal(await prisma.employeeAdvanceInstallment.count({ where: { batchId: batch.id } }), 0);
    await ok(await editSalary(req({ year: 2026, month: 9, payments: [payment] }, "PUT"), ctx(batch.id)));
    await ok(await statusSalary(req({ status: "CANCELLED" }, "PATCH"), ctx(batch.id)));
    assert.equal(await prisma.employeeAdvanceInstallment.count({ where: { batchId: batch.id } }), 0);
    assert.equal((await statusSalary(req({ status: "DRAFT" }, "PATCH"), ctx(batch.id))).status, 400);
    await ok(await deleteSalary(req({}, "DELETE"), ctx(batch.id)));
    const concurrent = await Promise.all([createSalary(req(salaryInput)), createSalary(req(salaryInput))]);
    assert.deepEqual(concurrent.map(result => result.status).sort(), [201, 400]);
    const paidBatch = await prisma.salaryBatch.findFirstOrThrow({ where: { companyId, month: 9, year: 2026 } });
    await ok(await statusSalary(req({ status: "APPROVED" }, "PATCH"), ctx(paidBatch.id)));
    await ok(await statusSalary(req({ status: "PAID" }, "PATCH"), ctx(paidBatch.id)));
    assert.equal((await editSalary(req({ year: 2026, month: 9, payments: [payment] }, "PUT"), ctx(paidBatch.id))).status, 400);
    assert.equal((await deleteSalary(req({}, "DELETE"), ctx(paidBatch.id))).status, 400);
    const installments = await prisma.employeeAdvanceInstallment.findMany({ where: { advanceId: advance.id }, include: { batch: true } });
    assert.equal(installments.filter(row => row.batch?.status === "PAID").reduce((sum, row) => sum + Number(row.amount), 0), 100);
    const next = await ok(await createSalary(req({ ...salaryInput, year: 2027, month: 1 })), 201);
    assert.equal(Number(next.payments[0].advanceDeduction), 75);
    const extra = await ok(await createAdvance(req({ ...input, amount: 12.345, installments: [{ year: 2027, month: 2, amount: 12.345 }] })), 201);
    await ok(await cancelAdvance(req({ id: extra.id }, "DELETE")));
    assert.equal((await prisma.employeeAdvance.findUniqueOrThrow({ where: { id: extra.id } })).isCancelled, true);
    assert.equal((await prisma.journalEntry.findUniqueOrThrow({ where: { id: extra.journalEntryId } })).isDeleted, true);
    const countBefore = await prisma.employeeAdvance.count({ where: { companyId } });
    await prisma.fiscalYear.updateMany({ where: { companyId, year: 2026 }, data: { isLocked: true } });
    assert.equal((await createAdvance(req({ ...input, amount: 1, installments: [{ year: 2027, month: 3, amount: 1 }] }))).status, 400);
    assert.equal(await prisma.employeeAdvance.count({ where: { companyId } }), countBefore, "Locked fiscal year rolls back the entire advance");
    console.log("PASS: precise schedules, disbursement and recovery journals, monthly preview, no duplicate deduction, edit/month change, cancellation, concurrency, paid protection and company isolation");
  } finally {
    const ids = [companyId, otherId];
    await prisma.employeeAdvanceInstallment.deleteMany({ where: { advance: { companyId: { in: ids } } } });
    await prisma.employeeAdvance.deleteMany({ where: { companyId: { in: ids } } });
    await prisma.salaryItem.deleteMany({ where: { batch: { companyId: { in: ids } } } });
    await prisma.salaryPayment.deleteMany({ where: { batch: { companyId: { in: ids } } } });
    await prisma.salaryBatch.deleteMany({ where: { companyId: { in: ids } } });
    await prisma.auditLog.deleteMany({ where: { OR: [{ companyId: { in: ids } }, { journalEntry: { companyId: { in: ids } } }] } });
    await prisma.journalEntryLine.deleteMany({ where: { journalEntry: { companyId: { in: ids } } } });
    await prisma.journalEntry.deleteMany({ where: { companyId: { in: ids } } });
    await prisma.employee.deleteMany({ where: { companyId: { in: ids } } });
    await prisma.chartOfAccount.updateMany({ where: { companyId: { in: ids } }, data: { parentId: null } });
    await prisma.chartOfAccount.deleteMany({ where: { companyId: { in: ids } } });
    await prisma.fiscalYear.deleteMany({ where: { companyId: { in: ids } } });
    await prisma.company.deleteMany({ where: { id: { in: ids } } });
  }
}
main().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => prisma.$disconnect());
